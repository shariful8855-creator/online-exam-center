create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists public.exams (
  id bigint generated by default as identity primary key,
  title text not null,
  subject text,
  duration_minutes integer not null default 30 check (duration_minutes > 0),
  published boolean not null default true,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  exam_id bigint not null references public.exams(id) on delete cascade,
  position integer not null,
  question_text text not null,
  options jsonb not null,
  correct_index integer not null check (correct_index between 0 and 3),
  explanation text,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

alter table public.admins enable row level security;
alter table public.exams enable row level security;
alter table public.questions enable row level security;

create policy "admins can read admin list" on public.admins
for select to authenticated using (public.is_admin());

create policy "public can read published exams" on public.exams
for select to anon, authenticated using (published = true or public.is_admin());

create policy "admins can create exams" on public.exams
for insert to authenticated with check (public.is_admin());

create policy "admins can update exams" on public.exams
for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "admins can delete exams" on public.exams
for delete to authenticated using (public.is_admin());

create policy "public can read questions for published exams" on public.questions
for select to anon, authenticated using (
  exists (select 1 from public.exams e where e.id = exam_id and (e.published = true or public.is_admin()))
);

create policy "admins can add questions" on public.questions
for insert to authenticated with check (public.is_admin());

create policy "admins can update questions" on public.questions
for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "admins can delete questions" on public.questions
for delete to authenticated using (public.is_admin());

grant usage on schema public to anon, authenticated;
grant select on public.exams, public.questions to anon, authenticated;
grant insert, update, delete on public.exams, public.questions to authenticated;
grant select on public.admins to authenticated;
grant usage, select on all sequences in schema public to authenticated;
